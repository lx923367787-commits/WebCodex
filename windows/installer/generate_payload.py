"""Generate exact NSIS install/uninstall inputs from one prepared payload."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path


BUILD = Path(__file__).resolve().parent
sys.path.insert(0, str(BUILD.parent))
from package_payload_policy import validate_payload_tree
REQUIRED = (
    "WebCodex.exe",
    "webcodex-runtime/webcodex.exe",
    "webcodex-runtime/webcodex-server.exe",
    "webcodex-runtime/webcodex-runner.exe",
    "mycodex-tools/python/python.exe",
    "mycodex-tools/plugin.py",
    "LICENSE",
)


def quote(value: str) -> str:
    return '"' + value.replace("$", "$$").replace('"', '$\\"') + '"'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--payload", type=Path, default=BUILD / "payload",
                        help="Prepared, credential-free Windows portable directory")
    parser.add_argument("--output-dir", type=Path, default=BUILD,
                        help="Directory for payload.nsh and payload-manifest.json")
    args = parser.parse_args()
    PAYLOAD = args.payload.absolute()
    output = args.output_dir.resolve()
    if (not PAYLOAD.is_dir() or PAYLOAD.is_symlink()
            or PAYLOAD.stat(follow_symlinks=False).st_file_attributes & 0x400):
        raise SystemExit("Expected a regular payload directory")
    for reserved in ("uninstall.exe", ".mycodex-install-owner"):
        if (PAYLOAD / reserved).exists():
            raise SystemExit(f"Remove old installation metadata from the prepared payload: {reserved}")
    if output == PAYLOAD or PAYLOAD in output.parents:
        raise SystemExit("Output directory must be outside the payload")
    validate_payload_tree(PAYLOAD)
    files: list[Path] = []
    directories: list[Path] = []
    for root, dirs, names in os.walk(PAYLOAD, followlinks=False):
        for name in dirs + names:
            path = Path(root) / name
            if path.is_symlink() or path.stat(follow_symlinks=False).st_file_attributes & 0x400:
                raise SystemExit(f"Reparse point is not allowed in payload: {path}")
            if path.is_file():
                files.append(path)
            elif path.is_dir():
                directories.append(path)
            else:
                raise SystemExit(f"Unsupported payload entry: {path}")
    files.sort(key=lambda path: path.relative_to(PAYLOAD).as_posix().casefold())
    if not files:
        raise SystemExit("Payload is empty")
    for relative in REQUIRED:
        if not (PAYLOAD / relative).is_file():
            raise SystemExit(f"Required payload file missing: {relative}")
    relatives = [str(path.relative_to(PAYLOAD)) for path in files]
    if len({path.casefold() for path in relatives}) != len(relatives):
        raise SystemExit("Case-insensitive duplicate paths in payload")

    lines = ["; Generated by generate_payload.py; do not edit.", "!macro InstallPayload"]
    active_parent: Path | None = None
    metadata = []
    for path in files:
        relative = path.relative_to(PAYLOAD)
        if relative.parent != active_parent:
            suffix = "" if relative.parent == Path(".") else "\\" + str(relative.parent)
            lines.append('  SetOutPath "$INSTDIR' + suffix.replace("$", "$$") + '"')
            active_parent = relative.parent
        lines.append("  File " + quote(str(path)))
        lines.append('  !insertmacro FailIfErrors "无法安装文件，请检查目录权限及可用磁盘空间。"')
        metadata.append({"path": relative.as_posix(), "size": path.stat().st_size,
                         "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    lines += ["!macroend", "", "!macro CheckUninstallPayload"]
    for path in files:
        relative = str(path.relative_to(PAYLOAD)).replace("$", "$$")
        lines += ['  Push "$INSTDIR\\' + relative + '"', "  Call un.CheckFileAvailable"]
    lines += ["!macroend", "", "!macro DeletePayload"]
    for path in files:
        relative = str(path.relative_to(PAYLOAD)).replace("$", "$$")
        lines += ['  Delete "$INSTDIR\\' + relative + '"',
                  '  !insertmacro FailIfErrors "无法删除程序文件；请退出 WebCodex 后重试卸载。"']
    for path in sorted(directories, key=lambda path: (-len(path.parts), str(path).casefold())):
        relative = str(path.relative_to(PAYLOAD)).replace("$", "$$")
        # No /r: anything created after installation is retained.
        lines += ['  RMDir "$INSTDIR\\' + relative + '"', "  ClearErrors"]
    lines += ["!macroend", ""]
    output.mkdir(parents=True, exist_ok=True)
    (output / "payload.nsh").write_text("\n".join(lines), encoding="utf-8-sig")
    (output / "payload-manifest.json").write_text(
        json.dumps({"file_count": len(files), "files": metadata}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps({"files": len(files), "bytes": sum(item["size"] for item in metadata)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
